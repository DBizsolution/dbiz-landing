/* Regenerates src/lib/svg-assets.ts from public/assets/svg/*.svg.
   The .svg files are the source of truth — edit them, then run:
     pnpm svg:gen
   Components import the named exports and render them via <InlineSvg>. */
import fs from 'node:fs'
import path from 'node:path'

const svgDir = 'public/assets/svg'
const outFile = 'src/lib/svg-assets.ts'

const toCamel = (name) =>
  name.replace(/\.svg$/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase())

const files = fs.readdirSync(svgDir).filter((f) => f.endsWith('.svg')).sort()

const header = `/* AUTO-GENERATED by scripts/generate-svg-modules.mjs — do not edit by hand.
   Source of truth: ${svgDir}/*.svg. Regenerate with \`pnpm svg:gen\`. */
`

const body = files
  .map((file) => {
    const content = fs
      .readFileSync(path.join(svgDir, file), 'utf8')
      .trim()
      .replace(/[\\`]|\$\{/g, (m) => `\\${m}`)
    return `export const ${toCamel(file)} = \`${content}\`\n`
  })
  .join('\n')

fs.writeFileSync(outFile, header + '\n' + body)
console.log(`wrote ${outFile} (${files.length} svgs)`)
